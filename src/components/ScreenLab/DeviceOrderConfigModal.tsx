import React, { useState, useEffect } from 'react';
import { 
  X, Check, RotateCcw, Sliders, ArrowLeft, ArrowRight, 
  Sparkles, ListOrdered, CheckCircle2, AlertCircle, Info, RefreshCw, Columns
} from 'lucide-react';

