export function getFormattedDateDdMmYy(d: Date = new Date()): string {
  const day = String(d.getDate()).padStart(2, '0');
  const month = String(d.getMonth() + 1).padStart(2, '0');
  const year = String(d.getFullYear()).slice(-2);
  return `${day}/${month}/${year}`;
}

export function getFirebaseServerTime(): string {
  return String(Date.now());
}

export function generateMcuId(serialNumber: number, vpAddress: number): string {
  const hexPart = (vpAddress & 0xffff).toString(16).toUpperCase().padStart(4, '0');
  const seqPart = String(serialNumber).padStart(3, '0');
  return `MCU-${seqPart}-${hexPart}`;
}

