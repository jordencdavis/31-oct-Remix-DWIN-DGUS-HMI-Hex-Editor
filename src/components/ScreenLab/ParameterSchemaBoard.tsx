export function autoGenerateHexValue(
  headerHex: string = '5A A5',
  vpAddress: number,
  valueStr: string,
  scale: number = 1,
  dataType: DwinDataType = 'UINT16'
): string {
  try {
    const s = scale || 1;
    const num = parseFloat(valueStr) || 0;
    // Calculate raw integer value for DGUS VP memory
    // When scale is 10 and value is 7.2 -> raw memory integer is 72 (0x0048)
    const rawVal = s > 1 ? Math.round(num * s) : Math.round(num);

    const is32Bit = dataType === 'UINT32' || dataType === 'INT32' || dataType === 'FLOAT32';

    const vpH = (vpAddress >> 8) & 0xff;
    const vpL = vpAddress & 0xff;

    const dataBytes: number[] = [];
    if (dataType === 'FLOAT32') {
      const buffer = new ArrayBuffer(4);
      new DataView(buffer).setFloat32(0, num, false); // big-endian
      const u8 = new Uint8Array(buffer);
      dataBytes.push(u8[0], u8[1], u8[2], u8[3]);
    } else if (is32Bit) {
      dataBytes.push(
        (rawVal >>> 24) & 0xff,
        (rawVal >>> 16) & 0xff,
        (rawVal >>> 8) & 0xff,
        rawVal & 0xff
      );
    } else {
      // 16-bit word
      dataBytes.push(
        (rawVal >> 8) & 0xff,
        rawVal & 0xff
      );
    }

    const payload = [0x82, vpH, vpL, ...dataBytes];
    const lenByte = payload.length;

    const normHeader = headerHex.trim() || '5A A5';
    const hexBytes = [
      ...normHeader.split(/\s+/),
      lenByte.toString(16).padStart(2, '0').toUpperCase(),
      ...payload.map(b => b.toString(16).padStart(2, '0').toUpperCase())
    ];

    return hexBytes.join(' ');
  } catch {
    return '5A A5 05 82 10 20 00 00';
  }
}

