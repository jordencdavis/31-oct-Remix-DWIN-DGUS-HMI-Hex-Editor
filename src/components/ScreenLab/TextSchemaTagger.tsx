export const STORAGE_TAGS_KEY = 'dwin_tagged_words_v2';

export interface TextSchemaTaggerProps {
  rawText: string;
  setRawText: (text: string) => void;
  onReParse?: (text: string) => void;
  taggedWords?: TaggedWordItem[];
  setTaggedWords?: React.Dispatch<React.SetStateAction<TaggedWordItem[]>>;
}

export const TextSchemaTagger: React.FC<TextSchemaTaggerProps> = ({
  rawText,
  setRawText,
  onReParse,
  taggedWords: externalTaggedWords,
  setTaggedWords: externalSetTaggedWords
}) => {
  // Selected Parameter Radio Button (defaults to 'parameterName')
  const [selectedCategoryId, setSelectedCategoryId] = useState<string>('parameterName');

  // Tagged words / phrases list with localStorage persistence
  const [internalTaggedWords, setInternalTaggedWords] = useState<TaggedWordItem[]>(() => {
    try {
      const saved = localStorage.getItem(STORAGE_TAGS_KEY);
      if (saved) {
        const parsed = JSON.parse(saved);
        if (Array.isArray(parsed) && parsed.length > 0) {
          return parsed;
        }
      }
    } catch {
      // ignore
    }
    return DEFAULT_SAMPLE_TAGS;
  });

  const taggedWords = externalTaggedWords ?? internalTaggedWords;
  const setTaggedWords = externalSetTaggedWords ?? setInternalTaggedWords;

  // Continuous selection history (not single item, cleared when radio button changes)
  const [selectedHistory, setSelectedHistory] = useState<{ id: string; text: string; timestamp: number }[]>([]);

  // View mode for the text box: 'interactive_tagging' | 'raw_editor'
  const [taggerViewMode, setTaggerViewMode] = useState<'interactive_tagging' | 'raw_editor'>('interactive_tagging');

  // Sidebar filter
  const [sidebarFilterCategory, setSidebarFilterCategory] = useState<string>('all');
  const [sidebarSearch, setSidebarSearch] = useState<string>('');

  // Editing state for an item in the sidebar
  const [editingTagId, setEditingTagId] = useState<string | null>(null);
  const [editingTextVal, setEditingTextVal] = useState<string>('');
  const [editingCategoryVal, setEditingCategoryVal] = useState<string>('parameterName');

  // Notification feedback
  const [toastMessage, setToastMessage] = useState<string | null>(null);

  const textViewerRef = useRef<HTMLDivElement>(null);
  const textareaRef = useRef<HTMLTextAreaElement>(null);

  // Sync tagged words to localStorage
  useEffect(() => {
    try {
      localStorage.setItem(STORAGE_TAGS_KEY, JSON.stringify(taggedWords));
    } catch {
      // ignore
    }
  }, [taggedWords]);

  const activeCategory = useMemo(() => {
    return SCHEMA_PARAM_CATEGORIES.find(c => c.id === selectedCategoryId) || SCHEMA_PARAM_CATEGORIES[3];
  }, [selectedCategoryId]);

  const showToast = (msg: string) => {
    setToastMessage(msg);
    setTimeout(() => setToastMessage(null), 2500);
  };

  // Add text to continuous selection history
  const addTextToHistory = (txt: string) => {
    const clean = txt.trim();
    if (!clean) return;

    setSelectedHistory(prev => {
      // Don't duplicate if exact same text was just added as the last item
      if (prev.length > 0 && prev[prev.length - 1].text === clean) {
        return prev;
      }
      return [
        ...prev,
        {
          id: `sel_${Date.now()}_${Math.random().toString(36).substring(2, 6)}`,
          text: clean,
          timestamp: Date.now()
        }
      ];
    });
  };

  // Remove individual item from selection history (with x mark)
  const removeSelectedHistoryItem = (id: string, e?: React.MouseEvent) => {
    if (e) e.stopPropagation();
    setSelectedHistory(prev => prev.filter(item => item.id !== id));
  };

  // Handle text selection in interactive view
  const handleInteractiveTextMouseUp = () => {
    const selection = window.getSelection();
    if (!selection || selection.isCollapsed) {
      return;
    }
    const txt = selection.toString().trim();
    if (txt) {
      addTextToHistory(txt);
    }
  };

  // Handle text selection in textarea view
  const handleTextareaSelect = (e: React.SyntheticEvent<HTMLTextAreaElement>) => {
    const target = e.currentTarget;
    const start = target.selectionStart;
    const end = target.selectionEnd;
    if (start !== end) {
      const txt = target.value.substring(start, end).trim();
      if (txt) {
        addTextToHistory(txt);
      }
    }
  };

  // Add tags from all continuous selection history items
  const handleTagSelection = () => {
    if (selectedHistory.length === 0) return;

    const newTags: TaggedWordItem[] = selectedHistory.map((item, idx) => ({
      id: `tag_${Date.now()}_${idx}_${Math.random().toString(36).substring(2, 6)}`,
      categoryId: activeCategory.id,
      categoryLabel: activeCategory.label,
      text: item.text,
      createdAt: Date.now() + idx
    }));

    setTaggedWords(prev => [...newTags, ...prev]);
    showToast(`Tagged ${newTags.length} item(s) as [${activeCategory.label}]`);
    setSelectedHistory([]);

    // Clear window selection
    if (window.getSelection) {
      window.getSelection()?.removeAllRanges();
    }
  };

  // Quick word click in interactive mode adds to continuous history
  const handleWordClick = (word: string, e: React.MouseEvent) => {
    e.stopPropagation();
    const clean = word.replace(/^[<>"'({[]+|[<>"')}\],;.]+$/g, '').trim();
    if (clean) {
      addTextToHistory(clean);
    }
  };

  // Delete tag
  const handleDeleteTag = (id: string, e?: React.MouseEvent) => {
    if (e) e.stopPropagation();
    setTaggedWords(prev => prev.filter(t => t.id !== id));
    if (editingTagId === id) {
      setEditingTagId(null);
    }
    showToast('Tag deleted');
  };

  // Start editing tag
  const handleStartEdit = (tag: TaggedWordItem, e: React.MouseEvent) => {
    e.stopPropagation();
    setEditingTagId(tag.id);
    setEditingTextVal(tag.text);
    setEditingCategoryVal(tag.categoryId);
  };

  // Save edited tag
  const handleSaveEdit = (e: React.FormEvent) => {
    e.preventDefault();
    if (!editingTagId || !editingTextVal.trim()) return;

    const cat = SCHEMA_PARAM_CATEGORIES.find(c => c.id === editingCategoryVal) || activeCategory;

    setTaggedWords(prev => prev.map(t => {
      if (t.id === editingTagId) {
        return {
          ...t,
          text: editingTextVal.trim(),
          categoryId: cat.id,
          categoryLabel: cat.label
        };
      }
      return t;
    }));

    setEditingTagId(null);
    showToast(`Updated tag to "${editingTextVal.trim()}" [${cat.label}]`);
  };

  // Cancel edit
  const handleCancelEdit = () => {
    setEditingTagId(null);
  };

  // Clear all tags
  const handleClearAllTags = () => {
    if (taggedWords.length === 0) return;
    if (window.confirm('Are you sure you want to clear all tagged parameter words?')) {
      setTaggedWords([]);
      showToast('All tagged words cleared');
    }
  };

  // Reset to default sample tags
  const handleResetSampleTags = () => {
    setTaggedWords(DEFAULT_SAMPLE_TAGS);
    showToast('Reset to sample tagged parameters');
  };

  // Filtered tags for sidebar
  const filteredTags = useMemo(() => {
    let list = taggedWords;
    if (sidebarFilterCategory !== 'all') {
      list = list.filter(t => t.categoryId === sidebarFilterCategory);
    }
    if (sidebarSearch.trim()) {
      const q = sidebarSearch.toLowerCase();
      list = list.filter(t => 
        t.text.toLowerCase().includes(q) || 
        t.categoryLabel.toLowerCase().includes(q)
      );
    }
    return list;
  }, [taggedWords, sidebarFilterCategory, sidebarSearch]);

  // Count tags per category for badges
  const categoryCounts = useMemo(() => {
    const counts: Record<string, number> = {};
    SCHEMA_PARAM_CATEGORIES.forEach(c => {
      counts[c.id] = 0;
    });
    taggedWords.forEach(t => {
      if (counts[t.categoryId] !== undefined) {
        counts[t.categoryId]++;
      }
    });
    return counts;
  }, [taggedWords]);

  // Export tagged items as JSON or CSV
  const handleExportTagsJson = () => {
    const dataStr = JSON.stringify(taggedWords, null, 2);
    const blob = new Blob([dataStr], { type: 'application/json' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = `tagged_parameters_${Date.now()}.json`;
    link.click();
    URL.revokeObjectURL(url);
  };

  const handleExportTagsCsv = () => {
    const headers = ['Serial #', 'Category ID', 'Category Label', 'Tagged Word/Text', 'Created Date'];
    const rows = taggedWords.map((t, idx) => [
      idx + 1,
      `"${t.categoryId}"`,
      `"${t.categoryLabel}"`,
      `"${t.text.replace(/"/g, '""')}"`,
      `"${new Date(t.createdAt).toISOString()}"`
    ]);
    const csvContent = [headers.join(','), ...rows.map(r => r.join(','))].join('\n');
    const blob = new Blob([csvContent], { type: 'text/csv' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = `tagged_parameters_${Date.now()}.csv`;
    link.click();
    URL.revokeObjectURL(url);
  };

  // Helper to render text with highlighted tagged words
  const renderHighlightedContent = () => {
    if (!rawText) {
      return (
        <div className="py-12 text-center text-slate-400 text-xs">
          No text file loaded. Paste raw text or upload a .txt file to tag parameters.
        </div>
      );
    }

    // Split text into lines
    const lines = rawText.split('\n');

    return (
      <div 
        ref={textViewerRef}
        onMouseUp={handleInteractiveTextMouseUp}
        className="font-mono text-xs leading-relaxed select-text space-y-1 max-h-[380px] overflow-y-auto p-3.5 bg-slate-50/70 border border-slate-200 rounded-lg text-slate-800"
      >
        {lines.map((line, lineIdx) => {
          if (!line.trim()) {
            return <div key={lineIdx} className="h-4 select-none" />;
          }

          // Check for staged / pending selection matches AND finally added tag matches
          const lineMatches: {
            type: 'staged' | 'final';
            staged?: { id: string; text: string; timestamp: number };
            tag?: TaggedWordItem;
            index: number;
            length: number;
          }[] = [];

          const lineLower = line.toLowerCase();

          // 1. Check staged / pending selections in selectedHistory first
          selectedHistory.forEach(sel => {
            if (!sel.text) return;
            let startPos = 0;
            const selLower = sel.text.toLowerCase();
            while (startPos < line.length) {
              const foundIdx = lineLower.indexOf(selLower, startPos);
              if (foundIdx === -1) break;
              lineMatches.push({
                type: 'staged',
                staged: sel,
                index: foundIdx,
                length: sel.text.length
              });
              startPos = foundIdx + sel.text.length;
            }
          });

          // 2. Check finally added taggedWords
          taggedWords.forEach(t => {
            if (!t.text) return;
            let startPos = 0;
            const tagLower = t.text.toLowerCase();
            while (startPos < line.length) {
              const foundIdx = lineLower.indexOf(tagLower, startPos);
              if (foundIdx === -1) break;
              lineMatches.push({
                type: 'final',
                tag: t,
                index: foundIdx,
                length: t.text.length
              });
              startPos = foundIdx + t.text.length;
            }
          });

          // Sort matches: by start index ascending; if same start, longer length first; if same length, staged first
          lineMatches.sort((a, b) => {
            if (a.index !== b.index) return a.index - b.index;
            if (b.length !== a.length) return b.length - a.length;
            return a.type === 'staged' ? -1 : 1;
          });

          // Non-overlapping segments
          const segments: React.ReactNode[] = [];
          let lastIdx = 0;

          lineMatches.forEach((match, mIdx) => {
            if (match.index < lastIdx) return; // skip overlap
            
            // Add untagged text before match
            if (match.index > lastIdx) {
              const untaggedSlice = line.substring(lastIdx, match.index);
              segments.push(
                <span key={`text_${lineIdx}_${mIdx}`}>
                  {untaggedSlice.split(/(\s+)/).map((part, pIdx) => {
                    if (part.trim()) {
                      return (
                        <span 
                          key={pIdx} 
                          onClick={(e) => handleWordClick(part, e)}
                          className="hover:bg-blue-100 hover:text-blue-900 rounded-xs px-0.5 cursor-pointer transition-colors"
                          title="Click to select word for tagging"
                        >
                          {part}
                        </span>
                      );
                    }
                    return part;
                  })}
                </span>
              );
            }

            const matchedText = line.substring(match.index, match.index + match.length);

            if (match.type === 'staged' && match.staged) {
              // Staged / Pending Selection Highlight (distinct amber color to indicate it is selected & added to process)
              segments.push(
                <span
                  key={`staged_${match.staged.id}_${lineIdx}_${mIdx}`}
                  className="inline-flex items-center gap-1 px-1.5 py-0.5 mx-0.5 rounded text-[11px] font-bold bg-amber-200/95 text-amber-950 border border-amber-400 ring-2 ring-amber-400/40 shadow-2xs cursor-pointer animate-in fade-in"
                  title={`Selected & added to header bar for processing as [${activeCategory.label}]. Click x to remove.`}
                  onClick={(e) => {
                    e.stopPropagation();
                  }}
                >
                  <span>{matchedText}</span>
                  <span className="text-[8.5px] uppercase tracking-wider font-mono px-1 py-0.2 rounded bg-amber-400/70 text-amber-950 font-bold select-none">
                    {activeCategory.shortLabel} · PENDING
                  </span>
                  <button
                    type="button"
                    onClick={(e) => removeSelectedHistoryItem(match.staged!.id, e)}
                    className="hover:opacity-100 opacity-70 p-0.5 hover:bg-amber-300 rounded-full cursor-pointer text-amber-900"
                    title="Remove from selection history"
                  >
                    <X className="w-2.5 h-2.5 stroke-[2.5]" />
                  </button>
                </span>
              );
            } else if (match.type === 'final' && match.tag) {
              // Finally Added Tagged Segment
              const categoryDef = SCHEMA_PARAM_CATEGORIES.find(c => c.id === match.tag!.categoryId) || activeCategory;
              segments.push(
                <span
                  key={`tag_${match.tag.id}_${lineIdx}_${mIdx}`}
                  className={`inline-flex items-center gap-1 px-1.5 py-0.5 mx-0.5 rounded text-[11px] font-semibold border shadow-2xs cursor-pointer ${categoryDef.highlightClass} ${categoryDef.badgeClass}`}
                  title={`Finally tagged as ${match.tag.categoryLabel}. Click to edit or delete.`}
                  onClick={(e) => {
                    e.stopPropagation();
                    addTextToHistory(matchedText);
                    setEditingTagId(match.tag!.id);
                    setEditingTextVal(match.tag!.text);
                    setEditingCategoryVal(match.tag!.categoryId);
                  }}
                >
                  <span>{matchedText}</span>
                  <span className="text-[9px] uppercase tracking-wider opacity-75 font-mono px-1 py-0.2 rounded bg-black/10">
                    {categoryDef.shortLabel}
                  </span>
                  <button
                    type="button"
                    onClick={(e) => handleDeleteTag(match.tag!.id, e)}
                    className="hover:opacity-100 opacity-60 p-0.5 hover:bg-black/10 rounded-full"
                    title="Remove tag"
                  >
                    <X className="w-2.5 h-2.5" />
                  </button>
                </span>
              );
            }

            lastIdx = match.index + match.length;
          });

          // Remaining trailing text on this line
          if (lastIdx < line.length) {
            const trailingText = line.substring(lastIdx);
            segments.push(
              <span key={`trail_${lineIdx}`}>
                {trailingText.split(/(\s+)/).map((part, pIdx) => {
                  if (part.trim()) {
                    return (
                      <span 
                        key={pIdx} 
                        onClick={(e) => handleWordClick(part, e)}
                        className="hover:bg-blue-100 hover:text-blue-900 rounded-xs px-0.5 cursor-pointer transition-colors"
                        title="Click to select word for tagging"
                      >
                        {part}
                      </span>
                    );
                  }
                  return part;
                })}
              </span>
            );
          }

          return (
            <div key={lineIdx} className="min-h-[1.3rem] hover:bg-slate-100/60 rounded px-1 -mx-1">
              <span className="inline-block w-6 text-right pr-1.5 text-slate-400 select-none text-[10px]">
                {lineIdx + 1}
              </span>
              {segments.length > 0 ? segments : line}
            </div>
          );
        })}
      </div>
    );
  };

  return (
    <div className="space-y-4 bg-slate-50/50 p-3 sm:p-4 rounded-xl border border-slate-200 shadow-2xs">
      {/* Toast Notification */}
      {toastMessage && (
        <div className="fixed bottom-4 right-4 z-50 bg-slate-900 text-white px-3.5 py-2 rounded-lg text-xs shadow-lg flex items-center gap-2 animate-in fade-in slide-in-from-bottom-2">
          <CheckCircle2 className="w-3.5 h-3.5 text-emerald-400" />
          <span>{toastMessage}</span>
        </div>
      )}

      {/* 1. Header & 10 Parameter Radio Buttons Toolbar */}
      <div className="bg-white border border-slate-200 rounded-xl p-4 shadow-xs space-y-3">
        <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-2 border-b border-slate-100 pb-2.5">
          <div className="flex items-center gap-2">
            <span className="p-1 rounded bg-blue-50 text-blue-600">
              <Tag className="w-4 h-4" />
            </span>
            <div>
              <div className="flex items-center gap-2">
                <h3 className="text-xs font-bold text-slate-900">
                  Design Export File Schema — Parameter Radio Selector
                </h3>
                <span className="text-[10px] font-mono px-2 py-0.5 rounded-full bg-blue-100 text-blue-800 font-semibold border border-blue-200">
                  10/10 Parameters Included
                </span>
              </div>
              <p className="text-[11px] text-slate-500">
                Select a radio button parameter, then highlight any word or group of words in the text below to tag it.
              </p>
            </div>
          </div>

          <div className="flex items-center gap-1.5 self-end sm:self-auto text-xs">
            <span className="text-[11px] text-slate-400 font-mono">
              Active: <strong className="text-slate-800 uppercase">{activeCategory.label}</strong>
            </span>
          </div>
        </div>

        {/* 10 Radio Buttons in a Single Row */}
        <div className="flex items-center gap-2 overflow-x-auto pb-1.5 custom-nav-scroll w-full flex-nowrap">
          {SCHEMA_PARAM_CATEGORIES.map((cat) => {
            const isSelected = selectedCategoryId === cat.id;
            const count = categoryCounts[cat.id] || 0;

            return (
              <label
                key={cat.id}
                onClick={() => {
                  if (selectedCategoryId !== cat.id) {
                    setSelectedCategoryId(cat.id);
                    setSelectedHistory([]); // clears continuous history and removes pending highlights in text
                    showToast(`Switched to [${cat.label}] — pending selections removed`);
                  }
                }}
                className={`flex items-center justify-between gap-1.5 px-2.5 py-1.5 rounded-lg border cursor-pointer transition-all text-xs select-none shrink-0 whitespace-nowrap ${
                  isSelected
                    ? `${cat.activeBgClass} ${cat.activeBorderClass} shadow-2xs font-semibold`
                    : `${cat.bgClass} ${cat.borderClass} hover:border-slate-400 text-slate-700 opacity-90`
                }`}
              >
                <div className="flex items-center gap-1.5 min-w-0">
                  <input
                    type="radio"
                    name="schema_parameter_radio"
                    value={cat.id}
                    checked={isSelected}
                    onChange={() => {
                      if (selectedCategoryId !== cat.id) {
                        setSelectedCategoryId(cat.id);
                        setSelectedHistory([]); // clears continuous history
                        showToast(`Switched to [${cat.label}] — pending selections removed`);
                      }
                    }}
                    className="w-3.5 h-3.5 text-blue-600 focus:ring-blue-500 border-slate-300 cursor-pointer shrink-0"
                  />
                  <span className={`text-[11px] font-bold ${isSelected ? cat.textClass : 'text-slate-800'}`}>
                    {cat.number}. {cat.label}
                  </span>
                </div>

                <span
                  className={`text-[10px] font-mono font-bold px-1.5 py-0.5 rounded-full shrink-0 border ml-1 ${
                    count > 0 
                      ? `${cat.badgeClass} shadow-2xs` 
                      : 'bg-white/80 text-slate-400 border-slate-200'
                  }`}
                  title={`${count} tagged items under ${cat.label}`}
                >
                  {count}
                </span>
              </label>
            );
          })}
        </div>
      </div>

      {/* 2. Interactive Selection Action Bar with Continuous History */}
      <div className="bg-white border border-slate-200 rounded-xl p-3 shadow-xs flex flex-col md:flex-row md:items-center justify-between gap-3">
        <div className="flex items-center gap-2 flex-wrap text-xs flex-1 min-w-0">
          <div className="flex items-center gap-1.5 font-semibold text-slate-700 shrink-0">
            <span>Selected History:</span>
            {selectedHistory.length > 0 && (
              <span className="text-[10px] font-mono font-bold px-1.5 py-0.2 rounded-full bg-amber-100 text-amber-900 border border-amber-300">
                {selectedHistory.length}
              </span>
            )}
          </div>

          {selectedHistory.length > 0 ? (
            <div className="flex items-center gap-1.5 flex-wrap">
              {selectedHistory.map((item, idx) => (
                <span
                  key={item.id}
                  className="inline-flex items-center gap-1.5 font-mono text-xs font-bold px-2.5 py-1 rounded-md bg-amber-50 text-amber-900 border border-amber-300 shadow-2xs group animate-in fade-in zoom-in-95"
                >
                  <span className="text-[10px] text-amber-600 font-normal select-none">#{idx + 1}</span>
                  <span className="truncate max-w-[200px]" title={item.text}>"{item.text}"</span>
                  <button
                    type="button"
                    onClick={(e) => removeSelectedHistoryItem(item.id, e)}
                    className="text-amber-700 hover:text-red-700 hover:bg-amber-200/80 p-0.5 rounded-full transition-colors cursor-pointer"
                    title={`Remove "${item.text}" from selection history`}
                  >
                    <X className="w-3.5 h-3.5 stroke-[2.5]" />
                  </button>
                </span>
              ))}
            </div>
          ) : (
            <span className="text-slate-400 italic text-[11px]">
              (Highlight words or phrases in the text below — each selected item is added to continuous history with an 'x' to remove, until another radio button is clicked)
            </span>
          )}
        </div>

        <div className="flex items-center gap-2 flex-wrap shrink-0">
          <button
            type="button"
            onClick={handleTagSelection}
            disabled={selectedHistory.length === 0}
            className={`flex items-center gap-1.5 px-3 py-1.5 rounded-lg text-xs font-bold transition-all shadow-xs cursor-pointer ${
              selectedHistory.length > 0
                ? 'bg-blue-600 hover:bg-blue-700 active:bg-blue-800 text-white'
                : 'bg-slate-100 text-slate-400 border border-slate-200 cursor-not-allowed'
            }`}
            title={selectedHistory.length > 0 ? `Tag all ${selectedHistory.length} selected item(s) as ${activeCategory.label}` : 'Select word(s) first'}
          >
            <Plus className="w-3.5 h-3.5 stroke-[3]" />
            <span>
              {selectedHistory.length > 1
                ? `Tag All (${selectedHistory.length}) as ${activeCategory.label}`
                : `Tag as ${activeCategory.label}`}
            </span>
          </button>

          {selectedHistory.length > 0 && (
            <button
              type="button"
              onClick={() => setSelectedHistory([])}
              className="flex items-center gap-1 px-2.5 py-1.5 rounded-lg text-xs text-slate-600 hover:text-slate-900 hover:bg-slate-100 border border-slate-200 cursor-pointer transition-colors"
              title="Clear continuous selection history"
            >
              <RotateCcw className="w-3.5 h-3.5 text-slate-400" />
              <span>Clear ({selectedHistory.length})</span>
            </button>
          )}
        </div>
      </div>

      {/* 3. Main Workspace: Text Content (Left) + Tagged Elements Sidebar (Right) */}
      <div className="flex flex-col lg:flex-row gap-4 items-start w-full">
        {/* Left Column: Text Area & Interactive Viewer */}
        <div className="flex-1 min-w-0 w-full bg-white border border-slate-200 rounded-xl p-4 shadow-xs space-y-3">
          {/* Top text controls */}
          <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-2 border-b border-slate-100 pb-2">
            <div className="flex items-center gap-2">
              <FileText className="w-4 h-4 text-slate-500" />
              <span className="text-xs font-bold text-slate-900">
                Text Source File
              </span>
              <span className="text-[10px] font-mono text-slate-400">
                ({rawText.length} chars · {rawText.split('\n').length} lines)
              </span>
            </div>

            <div className="flex items-center gap-2">
              {/* Mode switch */}
              <div className="flex items-center bg-slate-100 p-0.5 rounded-lg border border-slate-200 text-xs">
                <button
                  type="button"
                  onClick={() => setTaggerViewMode('interactive_tagging')}
                  className={`px-2.5 py-1 rounded font-medium transition-colors cursor-pointer ${
                    taggerViewMode === 'interactive_tagging'
                      ? 'bg-white text-blue-700 shadow-2xs font-bold'
                      : 'text-slate-600 hover:text-slate-900'
                  }`}
                >
                  Interactive Tagging View
                </button>
                <button
                  type="button"
                  onClick={() => setTaggerViewMode('raw_editor')}
                  className={`px-2.5 py-1 rounded font-medium transition-colors cursor-pointer ${
                    taggerViewMode === 'raw_editor'
                      ? 'bg-white text-blue-700 shadow-2xs font-bold'
                      : 'text-slate-600 hover:text-slate-900'
                  }`}
                >
                  Edit Raw Text
                </button>
              </div>

              {onReParse && (
                <button
                  type="button"
                  onClick={() => onReParse(rawText)}
                  className="flex items-center gap-1 px-2.5 py-1 rounded-md text-xs font-medium text-slate-700 bg-slate-100 hover:bg-slate-200 border border-slate-300 cursor-pointer transition-colors"
                  title="Re-parse HTML divs to canvas elements"
                >
                  <RotateCcw className="w-3 h-3 text-slate-500" />
                  <span>Re-Parse</span>
                </button>
              )}
            </div>
          </div>

          {/* Interactive Tagging Mode */}
          {taggerViewMode === 'interactive_tagging' && (
            <div className="space-y-2">
              <div className="text-[11px] text-slate-500 flex items-center justify-between">
                <span>
                  Tip: Highlight any word or phrase with your mouse, then click "Tag as {activeCategory.label}". Or click individual words.
                </span>
                <span className="text-[10px] text-emerald-700 font-medium">
                  {taggedWords.length} active tags
                </span>
              </div>
              {renderHighlightedContent()}
            </div>
          )}

          {/* Raw Editor Mode */}
          {taggerViewMode === 'raw_editor' && (
            <div className="space-y-2">
              <div className="text-[11px] text-slate-500 flex items-center justify-between">
                <span>Edit or paste text directly. Select any text inside to tag it to the active parameter.</span>
                <button
                  type="button"
                  onClick={() => setRawText('')}
                  className="text-xs text-red-600 hover:underline"
                >
                  Clear text
                </button>
              </div>
              <textarea
                ref={textareaRef}
                value={rawText}
                onChange={(e) => setRawText(e.target.value)}
                onSelect={handleTextareaSelect}
                placeholder="Paste raw DIV elements or parameter text here..."
                className="w-full h-80 p-3.5 font-mono text-xs bg-slate-50 text-slate-900 rounded-lg border border-slate-300 focus:outline-none focus:ring-2 focus:ring-blue-500 resize-y shadow-inner"
                spellCheck={false}
              />
            </div>
          )}
        </div>

        {/* Right Column: Tagged Elements Sidebar with Edit & Delete (CSS 1: width: 300px, padding-right: 16px, margin-right: 0px) */}
        <div 
          style={{ width: '300px', paddingRight: '16px', marginRight: '0px' }} 
          className="w-full lg:w-[300px] shrink-0 bg-white border border-slate-200 rounded-xl p-4 shadow-xs space-y-3"
        >
          {/* Sidebar Header */}
          <div className="flex items-center justify-between border-b border-slate-100 pb-2.5">
            <div className="flex items-center gap-1.5">
              <Layers className="w-4 h-4 text-blue-600" />
              <h4 className="text-xs font-bold text-slate-900">
                Tagged Parameters Sidebar
              </h4>
              <span className="text-[10px] font-mono px-2 py-0.5 rounded-full bg-slate-100 text-slate-700 font-semibold">
                {filteredTags.length}
              </span>
            </div>

            <div className="flex items-center gap-1">
              <button
                type="button"
                onClick={handleExportTagsJson}
                className="p-1 rounded text-slate-500 hover:text-slate-800 hover:bg-slate-100"
                title="Export tags as JSON"
              >
                <Download className="w-3.5 h-3.5" />
              </button>
              <button
                type="button"
                onClick={handleClearAllTags}
                disabled={taggedWords.length === 0}
                className="p-1 rounded text-slate-400 hover:text-red-600 hover:bg-red-50 disabled:opacity-40"
                title="Clear all tagged parameters"
              >
                <Trash2 className="w-3.5 h-3.5" />
              </button>
            </div>
          </div>

          {/* Filter Bar */}
          <div className="space-y-2">
            <div className="relative">
              <Search className="w-3 h-3 text-slate-400 absolute left-2.5 top-1/2 -translate-y-1/2" />
              <input
                type="text"
                value={sidebarSearch}
                onChange={(e) => setSidebarSearch(e.target.value)}
                placeholder="Search tagged words..."
                className="w-full text-xs pl-7 pr-2.5 py-1 rounded-md border border-slate-200 bg-slate-50 focus:bg-white focus:outline-none focus:ring-1 focus:ring-blue-500"
              />
            </div>

            {/* Category Filter Pills */}
            <div className="flex items-center gap-1 overflow-x-auto pb-1 text-[11px] custom-nav-scroll">
              <button
                type="button"
                onClick={() => setSidebarFilterCategory('all')}
                className={`px-2 py-0.5 rounded-md whitespace-nowrap text-[10px] font-semibold transition-colors cursor-pointer ${
                  sidebarFilterCategory === 'all'
                    ? 'bg-blue-600 text-white shadow-2xs'
                    : 'bg-slate-100 text-slate-600 hover:bg-slate-200'
                }`}
              >
                All ({taggedWords.length})
              </button>
              {SCHEMA_PARAM_CATEGORIES.map(cat => {
                const count = categoryCounts[cat.id] || 0;
                if (count === 0 && sidebarFilterCategory !== cat.id) return null;
                return (
                  <button
                    key={cat.id}
                    type="button"
                    onClick={() => setSidebarFilterCategory(cat.id)}
                    className={`px-2 py-0.5 rounded-md whitespace-nowrap text-[10px] font-semibold transition-colors cursor-pointer ${
                      sidebarFilterCategory === cat.id
                        ? 'bg-blue-600 text-white shadow-2xs'
                        : `${cat.badgeClass} hover:opacity-80`
                    }`}
                  >
                    {cat.shortLabel} ({count})
                  </button>
                );
              })}
            </div>
          </div>

          {/* Tagged Items List */}
          <div className="space-y-2 max-h-[380px] overflow-y-auto pr-1">
            {filteredTags.map((tag) => {
              const catDef = SCHEMA_PARAM_CATEGORIES.find(c => c.id === tag.categoryId) || activeCategory;
              const isEditing = editingTagId === tag.id;

              if (isEditing) {
                return (
                  <form
                    key={tag.id}
                    onSubmit={handleSaveEdit}
                    className="p-2.5 rounded-lg border-2 border-blue-400 bg-blue-50/50 space-y-2 shadow-xs"
                  >
                    <div className="text-[11px] font-bold text-blue-900 flex items-center justify-between">
                      <span>Edit Tagged Parameter</span>
                      <button
                        type="button"
                        onClick={handleCancelEdit}
                        className="text-slate-400 hover:text-slate-600"
                      >
                        <X className="w-3.5 h-3.5" />
                      </button>
                    </div>

                    <div>
                      <label className="block text-[10px] font-semibold text-slate-600 mb-0.5">
                        Tagged Text:
                      </label>
                      <input
                        type="text"
                        value={editingTextVal}
                        onChange={(e) => setEditingTextVal(e.target.value)}
                        className="w-full text-xs font-mono px-2 py-1 rounded border border-slate-300 bg-white focus:outline-none focus:ring-1 focus:ring-blue-500"
                        autoFocus
                      />
                    </div>

                    <div>
                      <label className="block text-[10px] font-semibold text-slate-600 mb-0.5">
                        Parameter Group:
                      </label>
                      <select
                        value={editingCategoryVal}
                        onChange={(e) => setEditingCategoryVal(e.target.value)}
                        className="w-full text-xs px-2 py-1 rounded border border-slate-300 bg-white focus:outline-none focus:ring-1 focus:ring-blue-500"
                      >
                        {SCHEMA_PARAM_CATEGORIES.map(c => (
                          <option key={c.id} value={c.id}>
                            {c.number}. {c.label}
                          </option>
                        ))}
                      </select>
                    </div>

                    <div className="flex items-center justify-end gap-1.5 pt-1">
                      <button
                        type="button"
                        onClick={handleCancelEdit}
                        className="px-2 py-1 text-[11px] rounded text-slate-600 hover:bg-slate-200/60"
                      >
                        Cancel
                      </button>
                      <button
                        type="submit"
                        className="px-2.5 py-1 text-[11px] font-bold rounded bg-blue-600 hover:bg-blue-700 text-white shadow-2xs"
                      >
                        Save
                      </button>
                    </div>
                  </form>
                );
              }

              return (
                <div
                  key={tag.id}
                  className="p-2.5 rounded-lg border border-slate-200 hover:border-slate-300 bg-white hover:bg-slate-50/80 transition-all shadow-2xs group space-y-1.5"
                >
                  <div className="flex items-center justify-between gap-1.5">
                    <span className={`text-[10px] font-bold px-1.5 py-0.5 rounded border ${catDef.badgeClass}`}>
                      {catDef.number}. {catDef.label}
                    </span>

                    {/* Action buttons: Edit & Delete */}
                    <div className="flex items-center gap-1 opacity-90 group-hover:opacity-100 transition-opacity">
                      <button
                        type="button"
                        onClick={(e) => handleStartEdit(tag, e)}
                        className="p-1 rounded text-slate-500 hover:text-blue-700 hover:bg-blue-50 cursor-pointer transition-colors"
                        title="Edit tagged text or parameter group"
                      >
                        <Edit3 className="w-3.5 h-3.5" />
                      </button>
                      <button
                        type="button"
                        onClick={(e) => handleDeleteTag(tag.id, e)}
                        className="p-1 rounded text-slate-500 hover:text-red-700 hover:bg-red-50 cursor-pointer transition-colors"
                        title="Delete tag"
                      >
                        <Trash2 className="w-3.5 h-3.5" />
                      </button>
                    </div>
                  </div>

                  <div className="font-mono text-xs font-semibold text-slate-900 bg-slate-50 px-2 py-1 rounded border border-slate-100 break-all">
                    "{tag.text}"
                  </div>
                </div>
              );
            })}

            {filteredTags.length === 0 && (
              <div className="py-8 text-center text-slate-400 space-y-2">
                <Tag className="w-6 h-6 mx-auto stroke-1 text-slate-300" />
                <div className="text-xs font-medium text-slate-600">No tagged words match</div>
                <p className="text-[11px] text-slate-400 max-w-xs mx-auto">
                  Select a radio button parameter above, then highlight any word in the text on the left to tag it.
                </p>
                {taggedWords.length === 0 && (
                  <button
                    type="button"
                    onClick={handleResetSampleTags}
                    className="mt-2 text-xs text-blue-600 hover:underline font-medium inline-block"
                  >
                    Load Sample Tagged Parameters
                  </button>
                )}
              </div>
            )}
          </div>

          {/* Sidebar Footer info */}
          <div className="border-t border-slate-100 pt-2 flex items-center justify-between text-[11px] text-slate-500">
            <span>Total: <strong>{taggedWords.length}</strong> tags</span>
            <button
              type="button"
              onClick={handleExportTagsCsv}
              className="text-blue-600 hover:underline cursor-pointer"
            >
              Export CSV
            </button>
          </div>
        </div>
      </div>
    </div>
  );
};
